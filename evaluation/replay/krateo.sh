#!/usr/bin/env bash
# Replays the controlled cases of the Krateo case study (../krateo/scenario/seeds*.yaml) on
# the replay API server. Krateo's CRDs are generated: one permissive CRD (no schema) per kind
# that the seeds or the Krateo Patterns use, because only the objects matter to the engine.
# Shim for core-provider: the status of the seeded CompositionDefinitions (generated
# apiVersion, kind and resource) and the CRD of the kinds they generate.
# The natural state of the case study (the Krateo install, the portal, the two compositions)
# is not replayed: score.sh keeps the ground-truth rows of the seeded namespaces only.
set -euo pipefail
source "$(dirname "$0")/env.sh"
K="$EVAL/krateo"

python3 - "$REPLAY_STATE/krateo-crds.yaml" "$K"/scenario/seeds.yaml "$K"/scenario/seeds-definitions.yaml \
  "$K"/scenario/seeds-compositions.yaml "$K"/patterns/*.yaml "$K"/patterns-v2/*.yaml <<'PY'
import sys, yaml
out, files = sys.argv[1], sys.argv[2:]
kinds = {}  # (group, version, kind) -> plural
def add(api, kind, plural=None):
    if not api or "/" not in api or kind in ("*", None) or api.startswith("v1"):
        return
    group, version = api.split("/")
    if not group.endswith("krateo.io"):
        return
    kinds.setdefault((group, version, kind), plural or kind.lower() + "s")
def walk(node):
    if isinstance(node, dict):
        if "apiVersion" in node and "kind" in node:
            add(node["apiVersion"], node["kind"], node.get("plural"))
        for v in node.values(): walk(v)
    elif isinstance(node, list):
        for v in node: walk(v)
import os
for f in files:
    if not os.path.exists(f):
        continue  # an empty glob
    for d in yaml.safe_load_all(open(f)):
        if not d: continue
        if d.get("kind") == "Pattern": walk(d["spec"])
        else: add(d["apiVersion"], d["kind"])
# generated by the seeded CompositionDefinitions (see the shim below)
add("composition.krateo.io/v1-2-5", "GithubScaffoldingWithCompositionPage", "githubscaffoldingwithcompositionpages")
add("composition.krateo.io/v1-4-3", "PortalCompositionPageGeneric", "portalcompositionpagegenerics")
docs = []
by_crd = {}
for (g, v, k), plural in sorted(kinds.items()):
    crd = by_crd.setdefault((g, plural), {
        "apiVersion": "apiextensions.k8s.io/v1", "kind": "CustomResourceDefinition",
        "metadata": {"name": f"{plural}.{g}"},
        "spec": {"group": g, "scope": "Namespaced", "names": {"kind": k, "plural": plural, "singular": k.lower(), "listKind": k + "List"},
                 "versions": []}})
    crd["spec"]["versions"].append({"name": v, "served": True, "storage": not crd["spec"]["versions"],
        "subresources": {"status": {}},
        "schema": {"openAPIV3Schema": {"type": "object", "x-kubernetes-preserve-unknown-fields": True}}})
yaml.safe_dump_all(list(by_crd.values()), open(out, "w"), sort_keys=False)
print(f"{len(by_crd)} Krateo CRDs", file=sys.stderr)
PY
kubectl apply --server-side --force-conflicts -f "$REPLAY_STATE/krateo-crds.yaml" >/dev/null
kubectl wait --for=condition=Established crd --all --timeout=60s >/dev/null
for f in seeds.yaml seeds-definitions.yaml seeds-compositions.yaml; do
  kubectl apply --server-side --force-conflicts -f "$K/scenario/$f" >/dev/null
done
status() { kubectl -n kp-krateo-a patch compositiondefinition "$1" --subresource=status --type=merge \
  -p "{\"status\":{\"apiVersion\":\"$2\",\"kind\":\"$3\",\"resource\":\"$4\"}}" >/dev/null; }
status github-scaffolding-with-composition-page composition.krateo.io/v1-2-5 GithubScaffoldingWithCompositionPage githubscaffoldingwithcompositionpages
status portal-composition-page-generic composition.krateo.io/v1-4-3 PortalCompositionPageGeneric portalcompositionpagegenerics
# Shim for the composition-dynamic-controller: the Panel that the chart of composition
# page-generic-a renders (probe-G7 row of the ground truth); the portal lists it through its
# krateo.io/portal-page label, not through a layout. Only the label's presence matters.
kubectl apply --server-side --force-conflicts -f - >/dev/null <<'YAML'
apiVersion: widgets.templates.krateo.io/v1beta1
kind: Panel
metadata:
  name: portalcompositionpagegeneric-page-generic-a-composition-panel
  namespace: kp-krateo-a
  labels: {krateo.io/portal-page: compositions}
spec:
  widgetData: {title: page-generic-a}
YAML
echo "Krateo seeds applied: $(kubectl get restactions.templates.krateo.io -A --no-headers | wc -l) RESTActions"
