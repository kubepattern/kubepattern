#!/usr/bin/env python3
"""RQ6: renders results/tables/comparison.tex (booktabs), KubePattern vs Kyverno side by side, from
results/comparison/{expressiveness,effectiveness,cost,staleness-summary}.csv and results/comparison/mutation/.
"""
import csv
import os

EVAL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
C = os.path.join(EVAL, "results", "comparison")


def rows(name):
    with open(os.path.join(C, name), newline="") as f:
        return list(csv.DictReader(f))


def main():
    ex = rows("expressiveness.csv")
    eff = rows("effectiveness.csv")
    cost = {r["component"]: r for r in rows("cost.csv")}
    st = {(r["tool"], r["direction"]): r for r in rows("staleness-summary.csv")}
    mut = rows("mutation/mutation.csv")

    s = lambda k: sum(int(r[k]) for r in ex)
    be = [r for r in ex if r["best_effort_loc"]]
    eq = [r for r in eff if r["set"] == "equivalent"]
    bf = [r for r in eff if r["set"] == "best-effort"]
    kp = next(v for k, v in cost.items() if k.startswith("kubepattern"))
    ky, rc = cost["TOTAL (4 controllers)"], cost["reports-controller"]
    f = lambda x: f"{float(x):,.0f}"
    lat = lambda tool: "/".join(f"{float(st[(tool, d)]['median_s']):.0f}" for d in ("appear", "disappear"))
    latmax = lambda tool: max(float(st[(tool, d)]["max_s"]) for d in ("appear", "disappear"))

    body = [
        ("\\multicolumn{3}{l}{\\emph{Expressiveness (14 smells)}}",),
        ("Specification lines (logic only)", f"{s('kp_loc')} ({s('kp_logic_loc')})",
         f"{s('kyv_loc')} ({s('kyv_logic_loc')}) + 189 (21 shared GCEs)"),
        ("Matching primitives / CEL predicates", s("kp_primitives"), s("cel_predicates")),
        ("CEL comprehensions / optional hops", "--", f"{s('comprehensions')} / {s('optional_hops')}"),
        ("Limitation probes resolved", "0/10 (as predicted)", f"10/10 (best-effort, {len(be)} policies)"),
        ("\\multicolumn{3}{l}{\\emph{Effectiveness (43 positives, 52 negatives)}}",),
        ("Precision / recall", "1.00 / 1.00", f"{eq[0]['precision']} / {eq[0]['recall']} (1:1), {bf[0]['precision']} / {bf[0]['recall']} (best-effort)"),
        ("Probes as predicted by KubePattern semantics", "10/10", f"{eq[0]['probes_as_engine']}/10 (1:1)"),
        ("Mutants killed and restored", "15/15", f"{sum(r['killed'] == 'True' and r['restored'] == 'True' for r in mut)}/{len(mut)}"),
        ("\\multicolumn{3}{l}{\\emph{Cost (one cycle every 300 s, 1 h window)}}",),
        ("Idle memory (MiB)", "0 (31 peak per run)", f"{f(ky['mem_median_mib'])} ({f(rc['mem_median_mib'])} reports ctrl.)"),
        ("CPU seconds per hour", kp["cpu_s_per_hour"], f"{f(ky['cpu_s_per_hour'])} ({f(rc['cpu_s_per_hour'])} reports ctrl.)"),
        ("API requests per cycle", f(kp["requests_per_cycle"]), f"{f(ky['requests_per_cycle'])} (reports ctrl. w/o leases: {f(rc['requests_per_cycle_no_lease'])})"),
        ("Output writes per cycle", f"{kp['smell-write_per_hour'] and round(float(kp['smell-write_per_hour']) / 12)} Smell updates",
         f"{round(float(rc['report-write_per_hour']) / 12)} report writes + {round(float(rc['event_per_hour']) / 12)} Events"),
        ("\\multicolumn{3}{l}{\\emph{Staleness after a dependency-side change}}",),
        ("Median latency appear/disappear (s)", lat("kubepattern"), lat("kyverno")),
        ("Maximum latency (s)", f"{latmax('kubepattern'):.0f}", f"{latmax('kyverno'):.0f}"),
    ]
    out = os.path.join(EVAL, "results", "tables", "comparison.tex")
    with open(out, "w") as fh:
        fh.write("% Generated by scripts/comparison_tables.py -- RQ6 KubePattern vs Kyverno\n")
        fh.write("\\begin{tabular}{lll}\n\\toprule\nMetric & KubePattern & Kyverno 1.19 \\\\\n\\midrule\n")
        for i, r in enumerate(body):
            if len(r) == 1:
                fh.write(("\\midrule\n" if i else "") + r[0] + " \\\\\n")
            else:
                fh.write(" & ".join(str(x) for x in r) + " \\\\\n")
        fh.write("\\bottomrule\n\\end{tabular}\n")
    print(open(out).read())


if __name__ == "__main__":
    main()
