#!/usr/bin/env python3
"""Renders the paper tables (booktabs LaTeX) from the CSV results into measurements/tables/.

  effectiveness.tex  RQ2 per-pattern scores          (measurements/effectiveness/scores.csv)
  expressiveness.tex RQ1 verdicts per limitation      (measurements/expressiveness/expressiveness.csv)
  timeline.tex       RQ5 scheduled runs               (measurements/cronjob/timeline.csv)
  scale.tex          RQ4 S1/S2/S3 sweeps              (measurements/scale/summary.csv)
"""
import csv
import os
from collections import Counter

EVAL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
R = os.path.join(EVAL, "measurements")
OUT = os.path.join(R, "tables")


def rows(path):
    with open(os.path.join(R, path), newline="") as f:
        return list(csv.DictReader(f))


def tt(x):
    return "\\texttt{" + x.replace("_", "\\_") + "}"


def table(name, spec, header, body, caption):
    with open(os.path.join(OUT, name), "w") as f:
        f.write(f"% Generated by scripts/make_tables.py -- {caption}\n\\begin{{tabular}}{{{spec}}}\n\\toprule\n")
        f.write(" & ".join(header) + " \\\\\n\\midrule\n")
        for line in body:
            f.write(("\\midrule\n" if line == "MIDRULE" else " & ".join(map(str, line)) + " \\\\\n"))
        f.write("\\bottomrule\n\\end{tabular}\n")


def main():
    os.makedirs(OUT, exist_ok=True)

    sc = rows("effectiveness/scores.csv")
    body = [[r["platform"], tt(r["pattern"]), r["positives"], r["negatives"], r["TP"], r["FP"], r["FN"], r["TN"],
             r["precision"], r["recall"], f"{r['probes_predicted']}/{r['probes']}"] for r in sc if r["pattern"] != "TOTAL"]
    t = next(r for r in sc if r["pattern"] == "TOTAL")
    body += ["MIDRULE", ["\\multicolumn{2}{l}{Total}", t["positives"], t["negatives"], t["TP"], t["FP"], t["FN"], t["TN"],
                         t["precision"], t["recall"], f"{t['probes_predicted']}/{t['probes']}"]]
    table("effectiveness.tex", "llrrrrrrrrr", ["Platform", "Pattern", "Pos", "Neg", "TP", "FP", "FN", "TN", "Prec.", "Rec.", "Probes"],
          body, "RQ2 effectiveness")

    ex = rows("expressiveness/expressiveness.csv")
    verdicts = Counter(r["verdict"] for r in ex)
    lim = Counter(l for r in ex if r["verdict"] != "expressible" for l in r["limitations"].split(";") if l)
    body = [[v, verdicts[v]] for v in ("expressible", "partial", "not expressible")] + ["MIDRULE"]
    body += [[f"blocked by {k}", n] for k, n in sorted(lim.items(), key=lambda x: (-x[1], x[0]))]
    table("expressiveness.tex", "lr", ["Verdict / limitation", f"Smells (of {len(ex)})"], body, "RQ1 expressiveness")

    tl = rows("cronjob/timeline.csv")
    body = [[r["run"], r["event_before_run"].replace("_", "\\_"), r["smells"], r["created"], r["kept_updated_in_place"],
             r["garbage_collected"], "yes" if r["matches_expected"] == "True" else "no"] for r in tl]
    table("timeline.tex", "rlrrrrc", ["Run", "Event before the run", "Smells", "Created", "Kept", "GC", "As predicted"], body, "RQ5 timeline")

    sm = rows("scale/summary.csv")
    body = []
    for exp, label in (("S1", "objects"), ("S2cold", "smells (cold)"), ("S2warm", "smells (warm)"), ("S2stale", "smells (stale)"), ("S3", "patterns")):
        for r in (x for x in sm if x["experiment"] == exp):
            body.append([label, r["cell"], r["objects"], r["smells"], r["wall_median_s"], r["rss_median_mb"], r["cpu_median_s"],
                         r["api_requests_median"], r["fetch_median_s"], r["write_median_s"], "yes" if r["timeouts"] != "0" else ""])
        body.append("MIDRULE")
    table("scale.tex", "llrrrrrrrrc", ["Sweep", "Cell", "Objects", "Smells", "Wall [s]", "RSS [MB]", "CPU [s]", "API req.",
                                       "Fetch [s]", "Write [s]", "Deadline"], body[:-1], "RQ4 scalability")
    print("tables written to", OUT, sorted(os.listdir(OUT)))


if __name__ == "__main__":
    main()
