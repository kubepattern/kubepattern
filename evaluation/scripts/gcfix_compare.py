#!/usr/bin/env python3
"""Before/after comparison of Smell garbage collection (engine as-is vs per-pattern prune).

Reads the archives produced by gcfix-remeasure.sh and the original RQ5 timeline, and writes
measurements/gcfix/compare.csv and measurements/tables/gcfix.tex with one row per scenario:
  D8        overlapping runs: Smells left after both runs (of the 46 expected)
  RQ5 run 5 narrowed RBAC: Smells of the skipped Kargo pattern that are garbage-collected
  RQ5 run 6 RBAC restored: Smells re-created as new objects
  RQ4 S=800 warm / warm2 above the throttling ceiling: DELETEs of valid Smells and Smell-set churn
  RQ4 stale all orphans fixed: DELETEs, wall time, and Smells still present after the run
"""
import csv
import json
import os
import re

EVAL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
R = os.path.join(EVAL, "measurements")


def rows(path):
    with open(os.path.join(R, path), newline="") as f:
        return list(csv.DictReader(f))


def smell_names(run_dir):
    items = json.load(open(os.path.join(run_dir, "smells.json")))["items"]
    return {s["metadata"]["name"]: s["metadata"]["uid"] for s in items}


def scale_cells(path):
    cells = {}
    for r in rows(path):
        cells[f"{r['experiment']}-{r['cell']}"] = {**r, "by_verb": json.loads(r["by_verb"])}
    return cells


def churn(cells, prev, cur):
    """Smells deleted/created between two consecutive runs on an unchanged cluster."""
    a, b = smell_names(cells[prev]["dir"]), smell_names(cells[cur]["dir"])
    return len(set(a) - set(b)), len(set(b) - set(a))


def d8(label):
    txt = open(os.path.join(R, "gcfix", f"concurrency-{label}.txt")).read()
    return int(re.search(r"(\d+) smells after both finished", txt).group(1))


def main():
    out = []
    before_tl, after_tl = rows("cronjob/timeline.csv"), rows("cronjob-fix/timeline.csv")
    sb, sa = scale_cells("gcfix/scale-before/runs.csv"), scale_cells("gcfix/scale-after/runs.csv")

    out.append(["D8 overlapping runs", "Smells left after both runs (of 46)", d8("before"), d8("after")])
    out.append(["RQ5 run 5 (RBAC narrowed)", "Smells garbage-collected", before_tl[4]["garbage_collected"], after_tl[4]["garbage_collected"]])
    out.append(["RQ5 run 6 (RBAC restored)", "Smells re-created as new objects", before_tl[5]["created"], after_tl[5]["created"]])
    for cell in ("S2warm-S800", "S2warm2-S800"):
        prev = "S2cold-S800" if cell == "S2warm-S800" else "S2warm-S800"
        db, cb = churn(sb, prev, cell)
        da, ca = churn(sa, prev, cell)
        tag = f"RQ4 S=800 {cell.split('-')[0][2:]}"
        out.append([tag, "valid Smells deleted vs previous run", db, da])
        out.append([tag, "Smells created vs previous run", cb, ca])
        out.append([tag, "Smells after the run (of 805)", sb[cell]["smells"], sa[cell]["smells"]])
    for cell in ("S2stale-S800", "S2stale2-S800"):
        tag = "stale" if cell == "S2stale-S800" else "stale (next run)"
        out.append([f"RQ4 S=800 {tag}", "DELETE requests", sb[cell]["by_verb"].get("delete", 0), sa[cell]["by_verb"].get("delete", 0)])
        out.append([f"RQ4 S=800 {tag}", "wall time [s]", sb[cell]["wall_s"], sa[cell]["wall_s"]])
        out.append([f"RQ4 S=800 {tag}", "Smells after the run (expected 5)", sb[cell]["smells"], sa[cell]["smells"]])

    os.makedirs(os.path.join(R, "gcfix"), exist_ok=True)
    with open(os.path.join(R, "gcfix", "compare.csv"), "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["scenario", "metric", "as-is (69d4ffd)", "per-pattern prune"])
        w.writerows(out)
    os.makedirs(os.path.join(R, "tables"), exist_ok=True)
    with open(os.path.join(R, "tables", "gcfix.tex"), "w") as f:
        f.write("% Generated by scripts/gcfix_compare.py -- Smell GC before/after\n\\begin{tabular}{llrr}\n\\toprule\n")
        f.write("Scenario & Metric & As-is & Per-pattern prune \\\\\n\\midrule\n")
        for r in out:
            f.write(" & ".join(str(x) for x in r) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n")
    width = max(len(r[0]) + len(r[1]) for r in out) + 3
    for r in out:
        print(f"{(r[0] + ' | ' + r[1]):{width}} {str(r[2]):>8} -> {r[3]}")


if __name__ == "__main__":
    main()
