#!/usr/bin/env python3
"""LaTeX tables of the engine update (client QPS, linter, spec.for) and of RQ8.

  measurements/tables/engine-update.tex  correctness and run time, per-pattern prune engine vs the updated engine
  measurements/tables/rq8.tex            RQ8 on kp-eval and Krateo: transient and persistent findings with and without spec.for

Inputs: measurements/regression/<commit>/, measurements/scale/, measurements/gcfix/scale-after/, measurements/qps/krateo/, measurements/rq8/.
Usage: engine_update_tables.py [<commit>]   (default 54dc498)
"""
import csv
import json
import os
import statistics
import sys

EVAL = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
C = sys.argv[1] if len(sys.argv) > 1 else "54dc498"
R = os.path.join(EVAL, "measurements")
REG = os.path.join(R, "regression", C)


def summary(path):
    return {(r["experiment"], r["cell"]): r for r in csv.DictReader(open(path))}


def median_wall(jsonl, engine):
    rows = [json.loads(l) for l in open(jsonl) if l.strip()]
    return statistics.median(r["wall_s"] for r in rows if r["engine"] == engine)


def engine_update():
    old, fix, new = summary(f"{R}/scale/summary.csv"), summary(f"{R}/gcfix/scale-after/summary.csv"), summary(f"{REG}/scale/summary.csv")
    sub = summary(f"{REG}/scale-subset/summary.csv")
    rows = [
        ("RQ2 (in-cluster, 4 runs)", "TP/FP/FN/TN, probes", "43/0/0/52, 10/10", "43/0/0/52, 10/10"),
        ("RQ2b mutation testing", "mutants killed, reverted = baseline", "15/15, yes", "15/15, yes"),
        ("D8 overlapping runs", "Smells left (of 46)", "46", "46"),
        ("RQ5 CronJob timeline", "runs as predicted", "9/9", "9/9"),
        ("Krateo, 3 in-cluster runs", "TP/FP/FN/TN, probes", "55/0/0/121, 25/25", "55/0/0/121, 25/25"),
        ("Krateo lifecycle", "expected changes seen", "26/26", "26/26"),
        ("Whole cluster (46 Smells)", "wall time [s], median of 3",
         f"{median_wall(f'{REG}/whole-cluster.jsonl', 'a814e4a'):.2f}", f"{median_wall(f'{REG}/whole-cluster.jsonl', C):.2f}"),
        ("Krateo whole cluster (61 Smells)", "wall time [s], median of 3",
         f"{median_wall(f'{R}/qps/krateo/runs.jsonl', 'a814e4a'):.2f}", f"{median_wall(f'{R}/qps/krateo/runs.jsonl', 'wp0'):.2f}"),
        ("RQ4 S=800 cold", "Smells written (of 805)", fix[("S2cold", "S800")]["smells"], sub[("S2cold", "S800")]["smells"]),
        ("RQ4 S=800 cold", "wall time [s]", fix[("S2cold", "S800")]["wall_median_s"], sub[("S2cold", "S800")]["wall_median_s"]),
        ("RQ4 S=800 cold", "deadline hit", "yes" if int(fix[("S2cold", "S800")]["timeouts"]) else "no",
         "yes" if int(sub[("S2cold", "S800")]["timeouts"]) else "no"),
        ("RQ4 S=800 stale", "wall time [s] (800 DELETEs)", fix[("S2stale", "S800")]["wall_median_s"], sub[("S2stale", "S800")]["wall_median_s"]),
        ("RQ4 S3 K=20", "wall time [s] (100 Smells)", old[("S3", "K20")]["wall_median_s"], new[("S3", "K20")]["wall_median_s"]),
        ("RQ4 S1 T=10000", "wall / CPU time [s]", f"{old[('S1', 'T10000')]['wall_median_s']} / {old[('S1', 'T10000')]['cpu_median_s']}",
         f"{new[('S1', 'T10000')]['wall_median_s']} / {new[('S1', 'T10000')]['cpu_median_s']}"),
    ]
    out = ["% Generated by scripts/engine_update_tables.py -- engine update (client QPS, linter, spec.for) vs per-pattern prune",
           r"\begin{tabular}{llrr}", r"\toprule", f"Check & Metric & Prune (\\texttt{{a814e4a}}, 5 QPS) & Updated (\\texttt{{{C}}}, 50 QPS) \\\\", r"\midrule"]
    out += [f"{a} & {b} & {c} & {d} \\\\" for a, b, c, d in rows]
    out += [r"\bottomrule", r"\end{tabular}", ""]
    open(f"{R}/tables/engine-update.tex", "w").write("\n".join(out))


def rq8():
    scores = list(csv.DictReader(open(f"{R}/rq8/eval/scores.csv")))
    tl = list(csv.DictReader(open(f"{R}/rq8/eval/timeline.csv")))
    events = {"dmt-rotated-v3": "T", "ci-web": "T", "ci-rq8-new": "P", "dmt-rotated-v2": "P"}

    def active(run, s, kind):
        return sorted(r["name"] for r in tl if r["run"] == run and r["set"] == s and r["phase"] == "Active" and events.get(r["name"]) == kind)

    out = ["% Generated by scripts/engine_update_tables.py -- RQ8: findings per run with and without spec.for (kp-eval, for: 4m, period 150 s)",
           r"\begin{tabular}{rrllll}", r"\toprule",
           r"Run & $t$ [s] & Seeded TP (no \texttt{for}) & Seeded TP (\texttt{for}, Active) & Transients Active (no / \texttt{for}) & New persistent Active (no / \texttt{for}) \\",
           r"\midrule"]
    for run in sorted({r["run"] for r in scores}, key=int):
        b = next(r for r in scores if r["run"] == run and r["set"] == "base")
        f = next(r for r in scores if r["run"] == run and r["set"] == "for")
        t_no, t_for = active(run, "base", "T"), active(run, "for", "T")
        p_no, p_for = active(run, "base", "P"), active(run, "for", "P")
        out.append(f"{run} & {b['t_s']} & {b['TP']}/{b['P']} & {f['TP']}/{f['P']} & {len(t_no)} / {len(t_for)} & {len(p_no)} / {len(p_for)} \\\\")
    k = list(csv.DictReader(open(f"{R}/rq8/krateo/timeline.csv")))
    trans = {"rq8-wip", "rq8-moved"}
    no_for = sum(1 for r in k if r["pattern"] == "paragraph-not-referenced" and r["name"] in trans and r["phase"] == "Active")
    with_for = sum(1 for r in k if r["pattern"].endswith("-for5m") and r["name"] in trans and r["phase"] == "Active")
    first_active = min(int(r["run"]) for r in k if r["pattern"].endswith("-for5m") and r["name"] == "rq8-stale" and r["phase"] == "Active")
    out += [r"\midrule",
            f"\\multicolumn{{6}}{{l}}{{Krateo (\\texttt{{for: 5m}}, period 180 s): transient Active findings {no_for} without \\texttt{{for}}, "
            f"{with_for} with it; the persistent widget is Active from run {first_active}.}} \\\\",
            r"\bottomrule", r"\end{tabular}", ""]
    open(f"{R}/tables/rq8.tex", "w").write("\n".join(out))


engine_update()
rq8()
print("wrote measurements/tables/engine-update.tex and measurements/tables/rq8.tex")
